-- This scripts contains queries used to generate 3 intermediate tables that will then be cleaned with Generate_final_df.py"
CREATE TABLE FINAL_MASTERTABLE AS
WITH delirium_table AS (
    SELECT 
        M."ADMISSION_ID",
        MAX(CASE
            WHEN EXTRACT(EPOCH FROM (M."DATETIME" - A."ICU_ADMIT_DATETIME")) / (60 * 60) <= 24 THEN 1
            ELSE 0
        END) AS DELIRIUM_FLAG_24H,
        MAX(CASE
            WHEN EXTRACT(EPOCH FROM (M."DATETIME" - A."ICU_ADMIT_DATETIME")) / (60 * 60) > 24 
             AND EXTRACT(EPOCH FROM (M."DATETIME" - A."ICU_ADMIT_DATETIME")) / (60 * 60) <= 48 THEN 1
            ELSE 0
        END) AS DELIRIUM_FLAG_24_48H,
        MAX(CASE
            WHEN EXTRACT(EPOCH FROM (M."DATETIME" - A."ICU_ADMIT_DATETIME")) / (60 * 60) > 48 THEN 1
            ELSE 0
        END) AS DELIRIUM_FLAG_48H_PLUS
    FROM 
        public."ADMISSIONS" A
        JOIN public."MEASUREMENTS" M ON A."ADMISSION_ID" = M."ADMISSION_ID"
    WHERE 
        "ICU_LOS_24H_FLAG" = 1
        AND M."ITEM_ID" = 'I007'
        AND M."VALUE_NUM" >= 4
    GROUP BY 
        M."ADMISSION_ID"
),
icu_table AS (
    SELECT A."PATIENT_ID", A."ADMISSION_ID", A."AGE_AT_ICU_ADMIT", P."GENDER",
        ROUND(EXTRACT(EPOCH FROM (A."ICU_DISCH_DATETIME" - A."ICU_ADMIT_DATETIME")) / (24 * 60 * 60), 1) AS ICU_LOS,
        ROUND(EXTRACT(EPOCH FROM (A."HOSP_DISCH_DATETIME" - A."HOSP_ADMIT_DATETIME")) / (24 * 60 * 60), 1) AS HOSP_LOS,
        A."ICU_EXPIRE_FLAG", 
        -- Adjust HOSP_EXPIRE_FLAG based on ICU_EXPIRE_FLAG
        CASE WHEN A."ICU_EXPIRE_FLAG" = 1 THEN 1 ELSE A."HOSP_EXPIRE_FLAG" END AS "HOSP_EXPIRE_FLAG",
        -- Calculate 30_DAYS_EXPIRE_FLAG based on ICU_EXPIRE_FLAG or HOSP_EXPIRE_FLAG
        CASE WHEN A."ICU_EXPIRE_FLAG" = 1 OR A."HOSP_EXPIRE_FLAG" = 1 THEN 1 ELSE A."30_DAYS_EXPIRE_FLAG" END AS "30_DAYS_EXPIRE_FLAG",
        A."DELIRIUM_FLAG"
    FROM public."ADMISSIONS" A
    JOIN public."PATIENTS" P ON A."PATIENT_ID" = P."PATIENT_ID"
    WHERE "ICU_LOS_24H_FLAG" = 1
)
SELECT ICU.*,  D.DELIRIUM_FLAG_24H, D.DELIRIUM_FLAG_24_48H, D.DELIRIUM_FLAG_48H_PLUS
FROM icu_table AS ICU
LEFT JOIN delirium_table AS D ON ICU."ADMISSION_ID" = D."ADMISSION_ID";



CREATE TABLE measurements_24_agg AS
SELECT
    M."ADMISSION_ID",
	M."ITEM_ID",
    IT."LABEL",
	IT."UOM",
    AVG(M."VALUE_NUM") AS AVERAGE_VALUE,
    MIN(M."VALUE_NUM") AS MIN_VALUE,
    MAX(M."VALUE_NUM") AS MAX_VALUE,
    PERCENTILE_CONT(0.25) WITHIN GROUP (ORDER BY M."VALUE_NUM") AS PERCENTILE_25,
    PERCENTILE_CONT(0.5) WITHIN GROUP (ORDER BY M."VALUE_NUM") AS MEDIAN_VALUE,
    PERCENTILE_CONT(0.75) WITHIN GROUP (ORDER BY M."VALUE_NUM") AS PERCENTILE_75,
    MAX(M."VALUE_NUM") - MIN(M."VALUE_NUM") AS RANGE,
    STDDEV(M."VALUE_NUM") AS STANDARD_DEVIATION,
    PERCENTILE_CONT(0.75) WITHIN GROUP (ORDER BY M."VALUE_NUM") - PERCENTILE_CONT(0.25) WITHIN GROUP (ORDER BY M."VALUE_NUM") AS IQR
FROM
    public."MEASUREMENTS" M
JOIN
    public."ITEMS" IT ON M."ITEM_ID" = IT."ITEM_ID"
GROUP BY
    M."ADMISSION_ID",
	M."ITEM_ID",
    IT."LABEL",
	IT."UOM";

CREATE TABLE interventions_24_agg AS
SELECT
    I."ADMISSION_ID",
	I."ITEM_ID",
	I."VALUE_CHAR",
	I."VALUE_NUM",
    IT."LABEL",
	IT."UOM",
    AVG(I."VALUE_NUM") AS AVERAGE_VALUE,
    MIN(I."VALUE_NUM") AS MIN_VALUE,
    MAX(I."VALUE_NUM") AS MAX_VALUE,
    PERCENTILE_CONT(0.25) WITHIN GROUP (ORDER BY I."VALUE_NUM") AS PERCENTILE_25,
    PERCENTILE_CONT(0.5) WITHIN GROUP (ORDER BY I."VALUE_NUM") AS MEDIAN_VALUE,
    PERCENTILE_CONT(0.75) WITHIN GROUP (ORDER BY I."VALUE_NUM") AS PERCENTILE_75,
    MAX(I."VALUE_NUM") - MIN(I."VALUE_NUM") AS RANGE,
    STDDEV(I."VALUE_NUM") AS STANDARD_DEVIATION,
    PERCENTILE_CONT(0.75) WITHIN GROUP (ORDER BY I."VALUE_NUM") - PERCENTILE_CONT(0.25) WITHIN GROUP (ORDER BY I."VALUE_NUM") AS IQR,
	CASE WHEN "VALUE_CHAR" IS NOT NULL OR "VALUE_NUM" IS NOT NULL THEN 1 ELSE 0 END AS HAS_NON_NULL_VALUE
FROM
    public."INTERVENTIONS" I
JOIN
    public."ITEMS" IT ON I."ITEM_ID" = IT."ITEM_ID"
GROUP BY
    I."ADMISSION_ID",
	I."ITEM_ID",
    IT."LABEL",
	I."VALUE_CHAR",
	I."VALUE_NUM",
	IT."UOM";

CREATE TABLE final_prescriptions AS
SELECT
    P."ADMISSION_ID",
	P."PRESCRIPTIONS_ID",
	P."ITEM_ID",
	P."DELTA_UOM",
	P."VALUE_UOM",
	P."RATE_UOM",
    IT."LABEL",
	IT."UOM",
	SUM(P."DELTA_TIME") AS TOTAL_TIME,
	SUM(P."VALUE_NUM") AS TOTAL_VOLUME,
    AVG(P."VALUE_NUM") AS AVERAGE_RATE,
    MIN(P."RATE_NUM") AS MIN_RATE,
    MAX(P."RATE_NUM") AS MAX_RATE,
    PERCENTILE_CONT(0.25) WITHIN GROUP (ORDER BY P."RATE_NUM") AS PERCENTILE_25_RATE,
    PERCENTILE_CONT(0.5) WITHIN GROUP (ORDER BY P."RATE_NUM") AS MEDIAN_VALUE_RATE,
    PERCENTILE_CONT(0.75) WITHIN GROUP (ORDER BY P."RATE_NUM") AS PERCENTILE_75_RATE,
    MAX(P."RATE_NUM") - MIN(P."RATE_NUM") AS RATE_RANGE,
    STDDEV(P."RATE_NUM") AS STANDARD_DEVIATION_RATE,
    PERCENTILE_CONT(0.75) WITHIN GROUP (ORDER BY P."RATE_NUM") - PERCENTILE_CONT(0.25) WITHIN GROUP (ORDER BY P."RATE_NUM") AS IQR_RATE
FROM
    public."PRESCRIPTIONS" P
JOIN
    public."ITEMS" IT ON P."ITEM_ID" = IT."ITEM_ID"
GROUP BY
    P."ADMISSION_ID",
	P."ITEM_ID",
	P."PRESCRIPTIONS_ID",
	P."DELTA_UOM",
	P."VALUE_UOM",
	P."RATE_UOM",
    IT."LABEL",
	IT."UOM";


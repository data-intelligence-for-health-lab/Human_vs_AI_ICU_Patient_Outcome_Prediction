-- This scripts contains queries used to generate FINAL_MASTER_TABLE (Join Outcomes from Delirium and AKI with other ICU outcomes )
CREATE TABLE FINAL_MASTERTABLE AS
WITH delirium_table AS (
    SELECT 
        M."ADMISSION_ID",
        MAX(CASE
            WHEN EXTRACT(EPOCH FROM (M."DATETIME" - A."ICU_ADMIT_DATETIME")) / (60 * 60) <= 24 THEN 1
            ELSE 0
        END) AS DELIRIUM_FLAG_24H,
        MAX(CASE
            WHEN EXTRACT(EPOCH FROM (M."DATETIME" - A."ICU_ADMIT_DATETIME")) / (60 * 60) > 24 
             AND EXTRACT(EPOCH FROM (M."DATETIME" - A."ICU_ADMIT_DATETIME")) / (60 * 60) <= 48 THEN 1
            ELSE 0
        END) AS DELIRIUM_FLAG_24_48H,
        MAX(CASE
            WHEN EXTRACT(EPOCH FROM (M."DATETIME" - A."ICU_ADMIT_DATETIME")) / (60 * 60) > 48 THEN 1
            ELSE 0
        END) AS DELIRIUM_FLAG_48H_PLUS
    FROM 
        public."ADMISSIONS" A
        JOIN public."MEASUREMENTS" M ON A."ADMISSION_ID" = M."ADMISSION_ID"
    WHERE 
        "ICU_LOS_24H_FLAG" = 1
        AND M."ITEM_ID" = 'I007'--ICDSC SCORE
        AND M."VALUE_NUM" >= 4
    GROUP BY 
        M."ADMISSION_ID"
),
icu_table AS (
    SELECT A."PATIENT_ID", A."ADMISSION_ID", A."AGE_AT_ICU_ADMIT", P."GENDER",
        ROUND(EXTRACT(EPOCH FROM (A."ICU_DISCH_DATETIME" - A."ICU_ADMIT_DATETIME")) / (24 * 60 * 60), 1) AS ICU_LOS,
        ROUND(EXTRACT(EPOCH FROM (A."HOSP_DISCH_DATETIME" - A."HOSP_ADMIT_DATETIME")) / (24 * 60 * 60), 1) AS HOSP_LOS,
        -- Adjust HOSP_MORTALITY based on ICU_EXPIRE_FLAG
        CASE WHEN A."ICU_EXPIRE_FLAG" = 1 THEN 1 ELSE A."HOSP_EXPIRE_FLAG" END AS "HOSP_MORTALITY",
        -- Derived 30_DAYS_POST_DISCHARGE_MORTALITY based on DOD and HOSP_DISCH_DATETIME
        CASE WHEN EXTRACT(EPOCH FROM (P."DOD" - A."HOSP_DISCH_DATETIME"))/ (60 * 60) <= 30 THEN 1 ELSE 0 END AS "30_DAYS_POST_DISCHARGE_MORTALITY"
    FROM public."ADMISSIONS" A
    JOIN public."PATIENTS" P ON A."PATIENT_ID" = P."PATIENT_ID"
    WHERE "ICU_LOS_24H_FLAG" = 1
)
SELECT ICU.*,  DELIRIUM.DELIRIUM_FLAG_24H, DELIRIUM.DELIRIUM_FLAG_24_48H, DELIRIUM.DELIRIUM_FLAG_48H_PLUS, AKI."AKI_STATUS_24H", AKI."AKI_STATUS_24_48H", AKI."AKI_STATUS_48H_PLUS" --AKI outcomes were generated in python then imported back to postgres
FROM icu_table AS ICU
LEFT JOIN "lu.kuang"."AKI_STATUS" AS AKI ON ICU."ADMISSION_ID" = AKI."ADMISSION_ID"
LEFT JOIN delirium_table AS DELIRIUM ON ICU."ADMISSION_ID" = DELIRIUM."ADMISSION_ID"
---WHERE "HOSP_MORTALITY" = 0 AND "30_DAYS_POST_DISCHARGE_MORTALITY" = 1 (249 cases)
DROP TABLE IF EXISTS "lu.kuang".final_prescriptions;
CREATE TABLE IF NOT EXISTS "lu.kuang".final_prescriptions AS
SELECT 
    P."ADMISSION_ID", 
    P."ITEM_ID", 
    SUM(P."DELTA_TIME") AS TOTAL_TIME,
    SUM(P."VALUE_NUM") AS TOTAL_VOLUME,
    AVG(P."VALUE_NUM") AS AVERAGE_VOLUME,
    MIN(P."VALUE_NUM") AS MIN_VOLUME,
    MAX(P."VALUE_NUM") AS MAX_VOLUME,
    AVG(P."RATE_NUM") AS AVERAGE_RATE,
    MIN(P."RATE_NUM") AS MIN_RATE,
    MAX(P."RATE_NUM") AS MAX_RATE,
	PERCENTILE_CONT(0.25) WITHIN GROUP (ORDER BY P."VALUE_NUM") AS PERCENTILE_25_VOLUME,
    PERCENTILE_CONT(0.5) WITHIN GROUP (ORDER BY P."VALUE_NUM") AS MEDIAN_VALUE_VOLUME,
    PERCENTILE_CONT(0.75) WITHIN GROUP (ORDER BY P."VALUE_NUM") AS PERCENTILE_75_VOLUME,
    MAX(P."VALUE_NUM") - MIN(P."VALUE_NUM") AS VOLUME_RANGE,
    STDDEV(P."VALUE_NUM") AS STANDARD_DEVIATION_VOLUME,
    PERCENTILE_CONT(0.75) WITHIN GROUP (ORDER BY P."VALUE_NUM") - PERCENTILE_CONT(0.25) WITHIN GROUP (ORDER BY P."VALUE_NUM") AS IQR_VOLUME,
    PERCENTILE_CONT(0.25) WITHIN GROUP (ORDER BY P."RATE_NUM") AS PERCENTILE_25_RATE,
    PERCENTILE_CONT(0.5) WITHIN GROUP (ORDER BY P."RATE_NUM") AS MEDIAN_VALUE_RATE,
    PERCENTILE_CONT(0.75) WITHIN GROUP (ORDER BY P."RATE_NUM") AS PERCENTILE_75_RATE,
    MAX(P."RATE_NUM") - MIN(P."RATE_NUM") AS RATE_RANGE,
    STDDEV(P."RATE_NUM") AS STANDARD_DEVIATION_RATE,
    PERCENTILE_CONT(0.75) WITHIN GROUP (ORDER BY P."RATE_NUM") - PERCENTILE_CONT(0.25) WITHIN GROUP (ORDER BY P."RATE_NUM") AS IQR_RATE
FROM 
    public."PRESCRIPTIONS" P 
JOIN 
    public."ADMISSIONS" A ON A."ADMISSION_ID" = P."ADMISSION_ID" 
WHERE 
    EXTRACT(epoch FROM P."START_DATETIME" - A."ICU_ADMIT_DATETIME") / 3600 < 24
GROUP BY
    P."ADMISSION_ID",
    P."ITEM_ID";
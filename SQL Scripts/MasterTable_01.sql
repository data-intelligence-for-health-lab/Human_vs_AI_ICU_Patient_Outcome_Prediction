DROP TABLE IF EXISTS "lu.kuang".FINAL_MASTERTABLE;

CREATE TABLE "lu.kuang".FINAL_MASTERTABLE AS
WITH delirium_table AS (
    SELECT 
        M."ADMISSION_ID",
        MAX(CASE
            WHEN EXTRACT(EPOCH FROM (M."DATETIME" - A."ICU_ADMIT_DATETIME")) / (60 * 60) <= 24 THEN 1
            ELSE 0
        END) AS DELIRIUM_FLAG_24H,
        MAX(CASE
            WHEN EXTRACT(EPOCH FROM (M."DATETIME" - A."ICU_ADMIT_DATETIME")) / (60 * 60) > 24 
             AND EXTRACT(EPOCH FROM (M."DATETIME" - A."ICU_ADMIT_DATETIME")) / (60 * 60) <= 48 THEN 1
            ELSE 0
        END) AS DELIRIUM_FLAG_24_48H,
        MAX(CASE
            WHEN EXTRACT(EPOCH FROM (M."DATETIME" - A."ICU_ADMIT_DATETIME")) / (60 * 60) > 48 THEN 1
            ELSE 0
        END) AS DELIRIUM_FLAG_48H_PLUS
    FROM 
        public."ADMISSIONS" A
        JOIN public."MEASUREMENTS" M ON A."ADMISSION_ID" = M."ADMISSION_ID"
    WHERE 
        "ICU_LOS_24H_FLAG" = 1
        AND M."ITEM_ID" = 'I007'
        AND M."VALUE_NUM" >= 4
    GROUP BY 
        M."ADMISSION_ID"
),
icu_table AS (
    SELECT A."PATIENT_ID", A."ADMISSION_ID", A."AGE_AT_ICU_ADMIT", P."GENDER",
        ROUND(EXTRACT(EPOCH FROM (A."ICU_DISCH_DATETIME" - A."ICU_ADMIT_DATETIME")) / (24 * 60 * 60), 1) AS ICU_LOS,
        ROUND(EXTRACT(EPOCH FROM (A."HOSP_DISCH_DATETIME" - A."HOSP_ADMIT_DATETIME")) / (24 * 60 * 60), 1) AS HOSP_LOS,
        A."ICU_EXPIRE_FLAG", 
        -- Adjust HOSP_EXPIRE_FLAG based on ICU_EXPIRE_FLAG
        CASE WHEN A."ICU_EXPIRE_FLAG" = 1 THEN 1 ELSE A."HOSP_EXPIRE_FLAG" END AS "HOSP_EXPIRE_FLAG",
        -- Calculate 30_DAYS_EXPIRE_FLAG based on ICU_EXPIRE_FLAG or HOSP_EXPIRE_FLAG
        CASE WHEN A."ICU_EXPIRE_FLAG" = 1 OR A."HOSP_EXPIRE_FLAG" = 1 THEN 1 ELSE A."30_DAYS_EXPIRE_FLAG" END AS "30_DAYS_EXPIRE_FLAG",
        A."DELIRIUM_FLAG"
    FROM public."ADMISSIONS" A
    JOIN public."PATIENTS" P ON A."PATIENT_ID" = P."PATIENT_ID"
    WHERE "ICU_LOS_24H_FLAG" = 1
)
SELECT ICU.*,  D.DELIRIUM_FLAG_24H, D.DELIRIUM_FLAG_24_48H, D.DELIRIUM_FLAG_48H_PLUS
FROM icu_table AS ICU
LEFT JOIN delirium_table AS D ON ICU."ADMISSION_ID" = D."ADMISSION_ID";
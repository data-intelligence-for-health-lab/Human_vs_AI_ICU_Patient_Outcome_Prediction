CREATE TABLE "lu.kuang".Delirium_Query_Table AS
SELECT m.*, a."HOSP_ADMIT_DATETIME", a."DELIRIUM_FLAG"
       EXTRACT(EPOCH FROM (m."DATETIME" - a."HOSP_ADMIT_DATETIME")) / 3600 AS "Measurement_Hour",
       CASE WHEN EXTRACT(EPOCH FROM (m."DATETIME" - a."HOSP_ADMIT_DATETIME")) / 3600 < 24 THEN TRUE ELSE FALSE END AS "<24 Hours",
       CASE WHEN EXTRACT(EPOCH FROM (m."DATETIME" - a."HOSP_ADMIT_DATETIME")) / 3600 >= 24 AND EXTRACT(EPOCH FROM (m."DATETIME" - a."HOSP_ADMIT_DATETIME")) / 3600 < 48 THEN TRUE ELSE FALSE END AS "24-48 Hours",
       CASE WHEN EXTRACT(EPOCH FROM (m."DATETIME" - a."HOSP_ADMIT_DATETIME")) / 3600 >= 48 THEN TRUE ELSE FALSE END AS ">= 48 Hours"
FROM public."MEASUREMENTS" AS m
JOIN public."ADMISSIONS" AS a
  ON m."ADMISSION_ID" = a."ADMISSION_ID"
WHERE m."ITEM_ID" = 'I007' AND m."VALUE_NUM" >= 4;
-- This script creates aggregated tables for measurements, interventions, and prescriptions
-- within the first 24 hours of ICU admission. It calculates various statistics
-- including average, minimum, maximum, percentiles, range, standard deviation, and IQR
-- This script also creates tables for categorical values in measurements and interventions to further cleaned in python
CREATE TABLE measurements_24_agg AS
SELECT
    M."ADMISSION_ID",
    M."ITEM_ID",
    AVG(M."VALUE_NUM") AS AVERAGE_VALUE,
    MIN(M."VALUE_NUM") AS MIN_VALUE,
    MAX(M."VALUE_NUM") AS MAX_VALUE,
    PERCENTILE_CONT(0.25) WITHIN GROUP (ORDER BY M."VALUE_NUM") AS PERCENTILE_25,
    PERCENTILE_CONT(0.5) WITHIN GROUP (ORDER BY M."VALUE_NUM") AS MEDIAN_VALUE,
    PERCENTILE_CONT(0.75) WITHIN GROUP (ORDER BY M."VALUE_NUM") AS PERCENTILE_75,
    MAX(M."VALUE_NUM") - MIN(M."VALUE_NUM") AS RANGE,
	COALESCE(STDDEV(M."VALUE_NUM"), 0) AS STANDARD_DEVIATION,
    PERCENTILE_CONT(0.75) WITHIN GROUP (ORDER BY M."VALUE_NUM") - 
    PERCENTILE_CONT(0.25) WITHIN GROUP (ORDER BY M."VALUE_NUM") AS IQR
FROM public."MEASUREMENTS" M
JOIN public."ITEMS" IT ON M."ITEM_ID" = IT."ITEM_ID"
JOIN public."ADMISSIONS" A ON M."ADMISSION_ID" = A."ADMISSION_ID"
WHERE M."VALUE_NUM" IS NOT NULL
  AND M."DATETIME" <= A."ICU_ADMIT_DATETIME" + INTERVAL '24 hours'
GROUP BY M."ADMISSION_ID", M."ITEM_ID";

CREATE TABLE interventions_24_agg AS
SELECT
    I."ADMISSION_ID",
    I."ITEM_ID",
    AVG(I."VALUE_NUM") AS AVERAGE_VALUE,
    MIN(I."VALUE_NUM") AS MIN_VALUE,
    MAX(I."VALUE_NUM") AS MAX_VALUE,
    PERCENTILE_CONT(0.25) WITHIN GROUP (ORDER BY I."VALUE_NUM") AS PERCENTILE_25,
    PERCENTILE_CONT(0.5) WITHIN GROUP (ORDER BY I."VALUE_NUM") AS MEDIAN_VALUE,
    PERCENTILE_CONT(0.75) WITHIN GROUP (ORDER BY I."VALUE_NUM") AS PERCENTILE_75,
    MAX(I."VALUE_NUM") - MIN(I."VALUE_NUM") AS RANGE,
	COALESCE(STDDEV(I."VALUE_NUM"), 0) AS STANDARD_DEVIATION,
    PERCENTILE_CONT(0.75) WITHIN GROUP (ORDER BY I."VALUE_NUM") 
      - PERCENTILE_CONT(0.25) WITHIN GROUP (ORDER BY I."VALUE_NUM") AS IQR
FROM
    public."INTERVENTIONS" I
JOIN
    public."ITEMS" IT ON I."ITEM_ID" = IT."ITEM_ID"
JOIN 
    public."ADMISSIONS" A ON I."ADMISSION_ID" = A."ADMISSION_ID"
WHERE 
    I."VALUE_NUM" IS NOT NULL
    AND I."START_DATETIME" <= A."ICU_ADMIT_DATETIME" + INTERVAL '24 hours'
GROUP BY
    I."ADMISSION_ID",
    I."ITEM_ID";

CREATE TABLE prescriptions_24_agg AS
SELECT
    P."ADMISSION_ID",
	P."ITEM_ID",
	SUM(P."DELTA_TIME") AS TOTAL_TIME,
	SUM(P."VALUE_NUM") AS TOTAL_VOLUME, 
    AVG(P."RATE_NUM") AS AVERAGE_RATE, --updated to RATE_NUM
    MIN(P."RATE_NUM") AS MIN_RATE,
    MAX(P."RATE_NUM") AS MAX_RATE,
    PERCENTILE_CONT(0.25) WITHIN GROUP (ORDER BY P."RATE_NUM") AS PERCENTILE_25_RATE,
    PERCENTILE_CONT(0.5) WITHIN GROUP (ORDER BY P."RATE_NUM") AS MEDIAN_VALUE_RATE,
    PERCENTILE_CONT(0.75) WITHIN GROUP (ORDER BY P."RATE_NUM") AS PERCENTILE_75_RATE,
    MAX(P."RATE_NUM") - MIN(P."RATE_NUM") AS RATE_RANGE,
	COALESCE(STDDEV(P."RATE_NUM"), 0) AS STANDARD_DEVIATION_RATE,
    PERCENTILE_CONT(0.75) WITHIN GROUP (ORDER BY P."RATE_NUM") - PERCENTILE_CONT(0.25) WITHIN GROUP (ORDER BY P."RATE_NUM") AS IQR_RATE
FROM
    public."PRESCRIPTIONS" P
JOIN
    public."ITEMS" IT ON P."ITEM_ID" = IT."ITEM_ID"
JOIN 
    public."ADMISSIONS" A ON P."ADMISSION_ID" = A."ADMISSION_ID"
WHERE 
    P."VALUE_NUM" IS NOT NULL
    AND P."START_DATETIME" <= A."ICU_ADMIT_DATETIME" + INTERVAL '24 hours'
GROUP BY
    P."ADMISSION_ID",
	P."ITEM_ID";

CREATE TABLE "lu.kuang"."INTERVENTIONS_VC_24hr" AS
WITH ItemFrequency AS (
    SELECT 
        I."ITEM_ID",
        COUNT(DISTINCT I."ADMISSION_ID") AS item_count
    FROM public."INTERVENTIONS" I
    GROUP BY I."ITEM_ID"
),
TotalAdmissions AS (
    SELECT COUNT(DISTINCT "ADMISSION_ID") AS total_admissions
    FROM public."ADMISSIONS"
),
FilteredItems AS (
    SELECT IFQ."ITEM_ID"
    FROM ItemFrequency IFQ
    CROSS JOIN TotalAdmissions TA
    WHERE IFQ.item_count > 0.7 * TA.total_admissions --filter to keep items with less than 30% missing 
)
SELECT
    I."ADMISSION_ID",
    I."ITEM_ID",
    I."START_DATETIME",
    I."VALUE_CHAR"
FROM public."INTERVENTIONS" I
JOIN public."ADMISSIONS" A 
    ON A."ADMISSION_ID" = I."ADMISSION_ID"
JOIN FilteredItems FIQ 
    ON I."ITEM_ID" = FIQ."ITEM_ID"
WHERE
    I."VALUE_NUM" IS NULL
    AND I."VALUE_CHAR" IS NOT NULL
    AND EXTRACT(epoch FROM I."START_DATETIME" - A."ICU_ADMIT_DATETIME") / 3600 < 24;